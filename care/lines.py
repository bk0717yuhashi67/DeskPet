# 兜底
DEFAULT_SCENE = "click_fun"


def pick(scene: str, salt: str = "", **fmt) -> str:
    """从场景里挑一条。用时间 + 场景做确定性轮换，避免连续重复。"""
    pool = SCENES.get(scene) or SCENES.get(DEFAULT_SCENE, ["…"])
    seed = f"{scene}|{salt}|{int(time.time() // 30)}"
    h = hashlib.md5(seed.encode("utf-8")).hexdigest()
    idx = int(h[:8], 16) % len(pool)
    text = pool[idx]
    if fmt:
        try:
            return text.format(**fmt)
        except (KeyError, IndexError):
            return text
    return text


def has(scene: str) -> bool:
    return scene in SCENES
